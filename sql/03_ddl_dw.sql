DROP TABLE IF EXISTS fact_penjualan;
DROP TABLE IF EXISTS dim_waktu;
DROP TABLE IF EXISTS dim_produk;
DROP TABLE IF EXISTS dim_pelanggan;

CREATE TABLE dim_waktu (
  date_sk INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL UNIQUE,
  hari INTEGER NOT NULL,
  nama_hari VARCHAR(20) NOT NULL,
  bulan INTEGER NOT NULL,
  nama_bulan VARCHAR(20) NOT NULL,
  kuartal INTEGER NOT NULL,
  tahun INTEGER NOT NULL
);

CREATE TABLE dim_produk (
  product_sk INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_produk VARCHAR(20) NOT NULL UNIQUE,
  nama_produk VARCHAR(150) NOT NULL,
  kategori VARCHAR(60) NOT NULL,
  merek VARCHAR(60)
);

CREATE TABLE dim_pelanggan (
  customer_sk INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pelanggan VARCHAR(20) NOT NULL UNIQUE,
  nama VARCHAR(150) NOT NULL,
  jenis_kelamin VARCHAR(20),
  kota VARCHAR(60) NOT NULL,
  provinsi VARCHAR(60),
  telepon VARCHAR(30)
);

CREATE TABLE fact_penjualan (
  fact_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transaksi VARCHAR(20) NOT NULL UNIQUE,
  tanggal DATE NOT NULL,
  date_sk INTEGER NOT NULL REFERENCES dim_waktu(date_sk),
  id_produk VARCHAR(20) NOT NULL,
  product_sk INTEGER NOT NULL REFERENCES dim_produk(product_sk),
  id_pelanggan VARCHAR(20) NOT NULL,
  customer_sk INTEGER NOT NULL REFERENCES dim_pelanggan(customer_sk),
  qty INTEGER NOT NULL CHECK (qty > 0),
  harga_satuan INTEGER NOT NULL CHECK (harga_satuan > 0),
  total_penjualan BIGINT NOT NULL,
  metode_bayar VARCHAR(20) NOT NULL
);

CREATE INDEX ix_fact_date_sk ON fact_penjualan(date_sk);
CREATE INDEX ix_fact_product_sk ON fact_penjualan(product_sk);
CREATE INDEX ix_fact_customer_sk ON fact_penjualan(customer_sk);
CREATE INDEX ix_fact_tanggal ON fact_penjualan(tanggal);
CREATE INDEX ix_fact_metode_bayar ON fact_penjualan(metode_bayar);
CREATE INDEX ix_dim_produk_kategori ON dim_produk(kategori);
CREATE INDEX ix_dim_pelanggan_kota ON dim_pelanggan(kota);
